package Builder.ash;

import java.util.ArrayList;
import java.util.Collections;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;

public final class ArrayInfo {

    private static final Map<Ast.VariableDecl, List<Ast.Expression>> SIZES =
        Collections.synchronizedMap(new IdentityHashMap<Ast.VariableDecl, List<Ast.Expression>>());

    private ArrayInfo() {}

    public static void put(Ast.VariableDecl d, List<Ast.Expression> sizes) {
        SIZES.put(d, sizes);
    }

    public static List<Ast.Expression> get(Ast.VariableDecl d) {
        List<Ast.Expression> s = SIZES.get(d);
        return s == null ? new ArrayList<Ast.Expression>() : s;
    }
}

