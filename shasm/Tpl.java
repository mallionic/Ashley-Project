package shasm;

import java.util.*;

public final class Tpl {
    public int id;
    public String mnem;
    public String[] ops;
    public boolean[] colon;
    public boolean[] star;
    public String[] slots;
    public List<String> tokens = new ArrayList<>();
    public Set<String> flags = new HashSet<>();
    public String src;
    public char dropLetter, srcLetter;

    public boolean has(String f) { return flags.contains(f); }
    public boolean tok(String t) { return tokens.contains(t); }
    @Override public String toString() { return src; }
}

